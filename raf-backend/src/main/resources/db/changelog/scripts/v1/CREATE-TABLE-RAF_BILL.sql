CREATE TABLE RAF_BILL (
    BILL_ID VARCHAR(15) PRIMARY KEY,
    BILL_NO VARCHAR(10),
    BILL_TITLE TEXT,
    INTRODUCED_DT DATE,
    LATEST_ACTION_DT DATE,
    LATEST_ACTION_TXT TEXT,
    POLICY_AREA VARCHAR(255),
    CONGRESS INT,
    BILL_TYPE VARCHAR(50),
    ORIGIN_CHAMBER VARCHAR(40),
    ORIGIN_CHAMBER_CD VARCHAR(4),
    SUMMARY_ACTION_DT DATE,
    SUMMARY_ACTION_DESC VARCHAR(255),
    SUMMARY_TXT TEXT,
    LAW_NO VARCHAR(12),
    LAW_TYPE VARCHAR(25),
    IS_LAW_FL VARCHAR(1),
    CREATE_TS TIMESTAMP,
    UPDATE_TS TIMESTAMP
);