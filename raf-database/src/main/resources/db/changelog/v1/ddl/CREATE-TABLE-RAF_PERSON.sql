CREATE TABLE RAF_PERSON (
    PERSON_ID VARCHAR(12) PRIMARY KEY,
    FIRST_NM VARCHAR(50) NOT NULL,
    MID_NM VARCHAR(50),
    LAST_NM VARCHAR(50) NOT NULL,
    FULL_NM VARCHAR(100),
    BIRTH_DT DATE,
    DTH_DT DATE,
    WEBSITE VARCHAR(100),
    OFFICE_LOC_LN1 VARCHAR(100),
    OFFICE_LOC_LN2 VARCHAR(100),
    PHONE VARCHAR(16),
    STATE VARCHAR(40),
    STATE_ABBR VARCHAR(3),
    CURRENT_DISTRICT int,
    CURRENT_MEM VARCHAR(6),
    BIO TEXT,
    EMAIL VARCHAR(100),
    IMG_URL VARCHAR(100),
    IMG_ATTRIBUTION VARCHAR(250),
    PARTY_MEM CHAR(1),
    PARTY VARCHAR(25),
    PARTY_ST_YR INT,
    CREATE_TS TIMESTAMP,
    UPDATE_TS TIMESTAMP
);
